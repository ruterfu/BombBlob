/** 浏览器首选语言 → 支持的语言 */
export function fromBrowser(tag) {
  const l = String(tag || '').toLowerCase();
  if (/(^|-)hk($|-)/.test(l)) return 'zh-HK';
  if (l.startsWith('zh')) return 'zh';
  if (l.startsWith('ja')) return 'ja';
  return 'en';
}

export function detectLang() {
  const saved = localStorage.getItem(KEY);
  if (LANGS.includes(saved)) return saved;
  return fromBrowser((navigator.languages && navigator.languages[0]) || navigator.language);
}

let lang = detectLang();
const listeners = new Set();

export function getLang() { return lang; }

export function normalizeLang(l) { return LANGS.includes(l) ? l : null; }

/** 切换语言：保存到本机并刷新界面（写回账号由 main.js 负责） */
export function setLang(l) {
  l = normalizeLang(l);
  if (!l) return;
  localStorage.setItem(KEY, l);
  if (l === lang) return;
  lang = l;
  applyI18n();
  for (const fn of listeners) fn(l);
}

export function onLangChange(fn) { listeners.add(fn); }

export function has(key) { return key in DICT[lang] || key in zh; }

export function t(key, params) {
  let s = DICT[lang][key] ?? en[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** 显示用名字：机器人代号按语言翻译 */
/** 机器人名字前缀：服务器统一存成「AI·代号」，显示时按语言换成「机器人·」「機械人·」「AI·」 */
const BOT_PREFIX = { zh: '机器人·', 'zh-HK': '機械人·', ja: 'AI·', en: 'AI·' };

export function displayName(name, isBot) {
  if (!isBot) return name;
  const n = String(name || '');
  const code = n.startsWith('AI·') ? n.slice(3) : '';
  if (!code) return name;
  return (BOT_PREFIX[lang] || 'AI·') + (BOT_NAMES[lang]?.[code] || code);
}

/** 地图名 / 描述（服务器下发 names / descs 多语言字段） */
export function mapText(map, field) {
  if (!map) return '';
  const all = map[field + 's'];
  return (all && (all[lang] || all.en)) || map[field] || '';
}

/** 刷新带 data-i18n / data-i18n-ph / data-i18n-title 标记的静态文本 */
export function applyI18n(root = document) {
  document.documentElement.lang = { zh: 'zh-CN', 'zh-HK': 'zh-HK', ja: 'ja', en: 'en' }[lang];
  document.title = t('doc.title');
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('.lang-seg button').forEach((b) => b.classList.toggle('on', b.dataset.lang === lang));
}
