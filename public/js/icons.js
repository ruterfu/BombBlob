/** 返回内联 SVG 字符串 */
export function icon(name, cls = '') {
  const d = ICONS[name] || ICONS.star;
  return `<svg class="ic ${cls}" viewBox="0 0 24 24" aria-hidden="true"><path d="${d}"/></svg>`;
}

/** 把所有 <i data-icon="xxx"> 替换为 SVG */
export function hydrateIcons(root = document) {
  root.querySelectorAll('i[data-icon]').forEach((el) => {
    el.outerHTML = icon(el.dataset.icon, el.className || '');
  });
}

/** 在 Canvas 上描绘图标 */
export function drawIcon(ctx, name, x, y, size, color = '#fff', width = 2) {
  const p = new Path2D(ICONS[name] || ICONS.star);
  ctx.save();
  ctx.translate(x - size / 2, y - size / 2);
  ctx.scale(size / 24, size / 24);
  ctx.strokeStyle = color;
  ctx.lineWidth = width;
  ctx.lineCap = 'round';
  ctx.lineJoin = 'round';
  ctx.stroke(p);
  ctx.restore();
}
